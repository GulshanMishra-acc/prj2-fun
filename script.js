function socialEntries(s={}) {
  const labels = {github:"GitHub",linkedin:"LinkedIn",instagram:"Instagram",portfolio:"Portfolio",youtube:"YouTube",email:"Email"};
  return Object.entries(s).filter(([k,v]) => v && String(v).trim()).map(([k,v]) => {
    let href = String(v).trim();
    if (k === "email" && !href.startsWith("mailto:")) href = "mailto:" + href;
    if (!/^(https?:\/\/|mailto:)/i.test(href)) href = "https://" + href;
    return `<a class="social-link" href="${esc(href)}" target="_blank" rel="noopener noreferrer"><span>${esc(labels[k] || k)} <span style="color:var(--muted);font-size:.78rem">↗</span></span><span>Open link</span></a>`;
  }).join("");
}
